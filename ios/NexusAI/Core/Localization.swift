enum AppLanguage: String, CaseIterable, Identifiable {
    case english = "en"
    case arabic = "ar"

    var id: String { rawValue }
    var label: String { self == .english ? "English" : "العربية" }
    var layoutDirection: LayoutDirection { self == .arabic ? .rightToLeft : .leftToRight }
}

struct Strings {
    let language: AppLanguage

    func text(_ key: String) -> String {
        let table = language == .arabic ? Strings.arabic : Strings.english
        return table[key] ?? Strings.english[key] ?? key
    }

